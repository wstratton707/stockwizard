"""docx_builder.py — Word (.docx) narrative equity brief.

A 2-3 page written report on a single stock — what the company does, a
performance overview, fundamentals, the Wall-Street analyst view, our DCF fair
value, a probabilistic forward outlook, and key risks — the kind of one-pager an
investor wants before buying. Reuses the data the Analysis page already computes,
so it's an on-demand export alongside the Excel and PowerPoint reports.

    from docx_builder import build_stock_docx
    buf = build_stock_docx(ticker, df, period_label, company_details=…, …)
    # buf is a BytesIO positioned at 0, ready for st.download_button
"""
